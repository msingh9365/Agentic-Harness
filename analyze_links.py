#!/usr/bin/env python
"""
Tables and a plot for the data-flow link study (measure_links.py).
Writes results/links/<prefix>tables.md and results/links/plots/<prefix>family_cross_chunk.png.

    python analyze_links.py                      # full run
    python analyze_links.py --prefix pilot2000_  # the 2,000-sample pilot
"""
import argparse
import os

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from analyze import style, BLUE, ORANGE, INK, INK2, SURF

R = "results/links"
WINDOW = 8


def pct(a, b):
    return 100.0 * a / b if b else float("nan")


def cnt(a, b):
    return f"{pct(a, b):.1f}% ({int(a):,})"


def bucket(n):
    return "1" if n == 1 else "2–3" if n <= 3 else "4–8" if n <= 8 else ">8"


def link_row(df, p=""):
    L = df[f"{p}n_links"].sum()
    return {
        "samples": f"{len(df):,}",
        "links": f"{int(L):,}",
        "links per sample (mean)": f"{L / max(1, len(df)):.1f}",
        "cross-chunk links": cnt(df[f"{p}n_cross_chunk_links"].sum(), L),
        "links leaving chunk 0": cnt(df[f"{p}n_links_leaving_chunk0"].sum(), L),
        "links with an end beyond chunk 7": cnt(df[f"{p}n_links_beyond_window"].sum(), L),
        "samples with ≥1 link": cnt((df[f"{p}n_links"] > 0).sum(), len(df)),
        "samples with ≥1 cross-chunk link": cnt((df[f"{p}n_cross_chunk_links"] > 0).sum(), len(df)),
    }


def table(rows, index_name):
    cols = list(next(iter(rows.values())).keys())
    out = f"| {index_name} | " + " | ".join(cols) + " |\n|" + "---|" * (len(cols) + 1) + "\n"
    for k, r in rows.items():
        out += f"| {k} | " + " | ".join(str(r[c]) for c in cols) + " |\n"
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prefix", default="")
    a = ap.parse_args()
    S = pd.read_csv(os.path.join(R, f"{a.prefix}samples.csv"))
    pairs = pd.read_csv(os.path.join(R, f"{a.prefix}pairs_cross_chunk.csv"))
    ok = S[S.status == "ok"].copy()
    ok["bucket"] = ok.n_chunks.map(bucket)
    md = [f"# Data-flow links between API calls ({'2,000-sample pilot' if a.prefix else 'full dataset'})\n",
          "Generated by `analyze_links.py` from `measure_links.py` output. Definitions are in REPORT.md §8.\n"]

    md.append("## Accounting\n")
    md.append(f"Samples measured: {len(ok):,} of {len(S):,} "
              f"(other statuses: {S[S.status != 'ok'].status.value_counts().to_dict() or 'none'}).\n\n")
    md.append(f"Token positions exact (pieces' ids joined == full report ids): {cnt((ok.fallback_used == 0).sum(), len(ok))}; "
              f"character-offset fallback used for {int(ok.fallback_used.sum()):,} samples.\n\n")
    md.append(f"API calls: {int(ok.n_calls.sum()):,} in total; median {np.median(ok.n_calls):.0f} per sample.\n")

    # 1. overall and per split
    md.append("\n## 1. Links overall and per split\n\n")
    md.append("Merged = over the API list as Nebula sees it (entry points merged, same order).\n\n")
    md.append(table({sp: link_row(ok if sp == "all" else ok[ok.split == sp]) for sp in ["all", "trainset", "testset"]}, "set"))
    md.append("\nWithin each entry point (links restarted in every entry point):\n\n")
    md.append(table({sp: link_row(ok if sp == "all" else ok[ok.split == sp], "ep_") for sp in ["all", "trainset", "testset"]}, "set"))
    md.append(f"\nMerged links whose producer and user are in different entry points: "
              f"{cnt(ok.n_links_across_ep.sum(), ok.n_links.sum())}.\n")

    # 2. per family and per length bucket
    md.append("\n## 2. Per family and per report length\n\n### 2a. Per family (merged links, all splits)\n\n")
    md.append(table({f: link_row(g) for f, g in ok.groupby("family")}, "family"))
    md.append("\n### 2b. Per report length (number of 512-token chunks, merged links)\n\n")
    md.append(table({b: link_row(ok[ok.bucket == b]) for b in ["1", "2–3", "4–8", ">8"] if (ok.bucket == b).any()}, "chunks"))
    md.append("\nReports that fit in one chunk cannot have cross-chunk links by definition.\n")

    # 3. chunk distance
    md.append("\n## 3. Chunk distance of cross-chunk links\n\n")
    tot = ok.n_cross_chunk_links.sum()
    md.append("| distance (chunks) | links | share of cross-chunk links |\n|---|---|---|\n")
    for d in range(1, WINDOW):
        md.append(f"| {d} | {int(ok[f'dist_{d}'].sum()):,} | {pct(ok[f'dist_{d}'].sum(), tot):.1f}% |\n")
    md.append(f"\nMax chunk distance per sample: median {np.median(ok.max_chunk_distance[ok.n_cross_chunk_links > 0]):.0f} "
              f"among samples with a cross-chunk link.\n")

    # 4. top pairs
    md.append("\n## 4. Top 20 (producer API → user API) pairs among cross-chunk links\n\n")
    md.append("| # | producer API | user API | links | share of cross-chunk links | samples |\n|---|---|---|---|---|---|\n")
    for i, r in enumerate(pairs.head(20).itertuples(), 1):
        md.append(f"| {i} | `{r.producer_api}` | `{r.user_api}` | {r.links:,} | {pct(r.links, tot):.1f}% | {r.samples:,} |\n")
    md.append(f"\nThe top 20 pairs cover {pct(pairs.head(20).links.sum(), tot):.1f}% of cross-chunk links; "
              f"{len(pairs):,} distinct pairs in total.\n")

    # 5. false-link check
    md.append("\n## 5. False-link check: producer must be a handle-creating API\n\n")
    md.append("Producer API name (without its DLL) starts with `Create`, `Open`, `Alloc`, `LoadLibrary`, "
              "`GetProcAddress`, `GetModuleHandle`, `RegOpen` or `RegCreate`, or is `socket` / `connect`.\n\n")
    md.append(table({"all links (as in §1)": link_row(ok), "handle-creating producers only": link_row(ok, "h_")}, "version"))
    md.append(f"\nShare of all links that have a handle-creating producer: {cnt(ok.h_n_links.sum(), ok.n_links.sum())}.\n\n")
    md.append("Per split, handle-creating producers only:\n\n")
    md.append(table({sp: link_row(ok[ok.split == sp], "h_") for sp in ["trainset", "testset"]}, "set"))

    # 6. chance baseline
    md.append("\n## 6. Chance baseline: calls shuffled within each sample\n\n")
    md.append("Each sample's API calls are put in a random order (one fixed shuffle per sample); links and token "
              "positions are recomputed. Ratio = real / shuffled. A ratio below 1 means real links cross chunks "
              "*less* often than in a random order, i.e. data flow is more local than chance.\n\n")
    md.append("| version | real links | shuffled links | real cross-chunk links | shuffled cross-chunk links | ratio (count) | "
              "real cross-chunk share | shuffled cross-chunk share | ratio (share) | real leaving chunk 0 | shuffled leaving chunk 0 |\n"
              "|---|---|---|---|---|---|---|---|---|---|---|\n")
    for name, p, q in [("all links", "", "shuf_"), ("handle-creating producers", "h_", "shuf_h_")]:
        for sp in ["all", "trainset", "testset"]:
            d = ok if sp == "all" else ok[ok.split == sp]
            rl, sl = d[f"{p}n_links"].sum(), d[f"{q}n_links"].sum()
            rc, sc = d[f"{p}n_cross_chunk_links"].sum(), d[f"{q}n_cross_chunk_links"].sum()
            r0, s0 = d[f"{p}n_links_leaving_chunk0"].sum(), d[f"{q}n_links_leaving_chunk0"].sum()
            md.append(f"| {name}, {sp} | {int(rl):,} | {int(sl):,} | {int(rc):,} | {int(sc):,} | {rc / sc:.2f} | "
                      f"{pct(rc, rl):.1f}% | {pct(sc, sl):.1f}% | {pct(rc, rl) / pct(sc, sl):.2f} | "
                      f"{pct(r0, rl):.1f}% | {pct(s0, sl):.1f}% |\n")
    md.append("\nAmong reports longer than one chunk only (where crossing is possible):\n\n")
    long = ok[ok.n_chunks > 1]
    md.append("| version | samples | real cross-chunk share | shuffled cross-chunk share | ratio (share) |\n|---|---|---|---|---|\n")
    for name, p, q in [("all links", "", "shuf_"), ("handle-creating producers", "h_", "shuf_h_")]:
        rs = pct(long[f"{p}n_cross_chunk_links"].sum(), long[f"{p}n_links"].sum())
        ss = pct(long[f"{q}n_cross_chunk_links"].sum(), long[f"{q}n_links"].sum())
        md.append(f"| {name} | {len(long):,} | {rs:.1f}% | {ss:.1f}% | {rs / ss:.2f} |\n")

    with open(os.path.join(R, f"{a.prefix}tables.md"), "w") as fh:
        fh.write("".join(md))

    # plot: per-family share of cross-chunk links
    os.makedirs(os.path.join(R, "plots"), exist_ok=True)
    fam = ok.groupby("family").agg(L=("n_links", "sum"), C=("n_cross_chunk_links", "sum"),
                                   hL=("h_n_links", "sum"), hC=("h_n_cross_chunk_links", "sum"))
    fam["all"] = 100 * fam.C / fam.L
    fam["h"] = 100 * fam.hC / fam.hL
    fam = fam.sort_values("all")
    plt.rcParams.update({"font.size": 10, "axes.titlesize": 11, "axes.titleweight": "bold",
                         "axes.labelcolor": INK2, "text.color": INK, "figure.facecolor": SURF})
    fig, ax = plt.subplots(figsize=(8, 4.6)); style(ax)
    y = np.arange(len(fam)); h = 0.38
    ax.barh(y - h / 2, fam["all"], h, color=BLUE, label="all links")
    ax.barh(y + h / 2, fam["h"], h, color=ORANGE, label="handle-creating producers only")
    for yi, v in zip(y - h / 2, fam["all"]):
        ax.text(v + 0.5, yi, f"{v:.1f}%", va="center", fontsize=8)
    for yi, v in zip(y + h / 2, fam["h"]):
        ax.text(v + 0.5, yi, f"{v:.1f}%", va="center", fontsize=8)
    overall = pct(ok.n_cross_chunk_links.sum(), ok.n_links.sum())
    ax.axvline(overall, color=INK2, ls=":", lw=1)
    ax.text(overall + 0.3, len(fam) - 0.4, f"all samples {overall:.1f}%", fontsize=8, color=INK2)
    ax.set_yticks(y, [f"{f} (n={int((ok.family == f).sum()):,})" for f in fam.index], fontsize=8)
    ax.set_xlabel("share of data-flow links whose producer and user are in different 512-token chunks (%)")
    ax.set_xlim(0, max(fam[["all", "h"]].max()) * 1.2 + 1)
    ax.set_title("Cross-chunk data-flow links per family"); ax.legend(frameon=False, loc="lower right", fontsize=8)
    fig.tight_layout(); fig.savefig(os.path.join(R, "plots", f"{a.prefix}family_cross_chunk.png"), dpi=150); plt.close(fig)
    print("wrote", os.path.join(R, f"{a.prefix}tables.md"))


if __name__ == "__main__":
    main()
