#!/usr/bin/env python
"""
Build a Kaggle kernel folder (run.py + kernel-metadata.json) for one job.   (OURS)

The kernel script is self-contained: it carries our code (baseline/) and the patches as a base64 tarball, so the exact
code that ran is the code in the pushed kernel version. At run time it
  1. unpacks our code to /tmp/kcode,
  2. pip-installs what the authors' package needs (Lightning etc.),
  3. clones the authors' repository at the PINNED commit and applies patches/*.patch,
  4. runs `python -m baseline.<job> <args>` with outputs in /kaggle/working/out.

Usage:
  python baseline/kaggle/build_kernel.py --slug nebula-preprocess --job preprocess --args "--out /kaggle/working/out" \
         --datasets dmitrijstrizna/quo-vadis-malware-emulation [--gpu] [--kernels owner/slug]
  kaggle kernels push -p baseline/kaggle/jobs/nebula-preprocess [--accelerator NvidiaTeslaT4]
"""
import argparse
import base64
import io
import json
import os
import tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OWNER = os.environ.get("KAGGLE_OWNER", "msingh9365")             # the account that pushes the kernel (KAGGLE_OWNER overrides)
PINNED = "1343ae170ef32b01a75d2dd5fb906b5541f073df"

BOOTSTRAP = r'''# generated by baseline/kaggle/build_kernel.py -- do not edit; edit baseline/ and rebuild
import base64, io, os, subprocess, sys, tarfile, time

PAYLOAD = "__PAYLOAD__"
JOB, ARGS = "__JOB__", "__ARGS__"
PINNED = "__PINNED__"
CODE, NEB = "/tmp/kcode", "/tmp/nebula"

def sh(cmd, check=True):
    t = time.time()
    r = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    tail = (r.stdout + r.stderr).strip()[-1200:]
    print(f"$ {cmd[:150]}   [exit {r.returncode}, {time.time() - t:.0f}s]" + (f"\n{tail}" if r.returncode else ""), flush=True)
    if check and r.returncode:
        raise SystemExit(f"setup step failed: {cmd[:100]}")

os.makedirs(CODE, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(PAYLOAD)), mode="r:gz").extractall(CODE)
sh("pip install -q lightning torchmetrics tensorboard sentencepiece orjson nltk speakeasy-emulator lief lxml scikit-learn matplotlib")
sh(f"rm -rf {NEB} && git clone -q https://github.com/dtrizna/nebula {NEB} && git -C {NEB} checkout -q {PINNED}")
sh(f"bash {CODE}/patches/apply_patches.sh {NEB}")
sh(f"pip install -q -e {NEB} --no-deps")
print("nebula commit:", subprocess.check_output(["git", "-C", NEB, "rev-parse", "HEAD"], text=True).strip(), flush=True)
env = dict(os.environ, PYTHONPATH=CODE, NEBULA_ROOT=NEB, PYTHONUNBUFFERED="1", TQDM_DISABLE="1")
os.makedirs("/kaggle/working/out", exist_ok=True)
cmd = [sys.executable, "-m", f"baseline.{JOB}"] + ARGS.split()
print("RUN:", " ".join(cmd), flush=True)
rc = subprocess.call(cmd, env=env, cwd=CODE)
print("job exit code:", rc, flush=True)
if rc:
    raise SystemExit(rc)
'''


def payload():
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for base in ["baseline", "patches"]:
            for dp, dn, fn in os.walk(os.path.join(ROOT, base)):
                dn[:] = [d for d in dn if d not in ("__pycache__", "jobs", "results") and not d.startswith(".")]
                for f in fn:
                    if f.endswith((".py", ".patch", ".sh", "ssl_split_hashes.json", "gap_split_hash.json", "b3_split_hashes.json", "b1_split_data.npz")):
                        full = os.path.join(dp, f)
                        tar.add(full, arcname=os.path.relpath(full, ROOT))
    return base64.b64encode(buf.getvalue()).decode()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--slug", required=True)
    ap.add_argument("--job", required=True, help="module under baseline/ (preprocess, detect, ssl, classify, ablate)")
    ap.add_argument("--args", default="")
    ap.add_argument("--gpu", action="store_true")
    ap.add_argument("--datasets", default="")
    ap.add_argument("--kernels", default="")
    ap.add_argument("--title", default=None)
    a = ap.parse_args()
    out = os.path.join(HERE, "jobs", a.slug)
    os.makedirs(out, exist_ok=True)
    code = BOOTSTRAP.replace("__PAYLOAD__", payload()).replace("__JOB__", a.job).replace("__ARGS__", a.args).replace("__PINNED__", PINNED)
    with open(os.path.join(out, "run.py"), "w") as f:
        f.write(code)
    meta = {"id": f"{OWNER}/{a.slug}", "title": a.title or a.slug, "code_file": "run.py", "language": "python",
            "kernel_type": "script", "is_private": "true", "enable_gpu": "true" if a.gpu else "false", "enable_tpu": "false",
            "enable_internet": "true", "machine_shape": "",
            "dataset_sources": [d for d in a.datasets.split(",") if d], "competition_sources": [],
            "kernel_sources": [k for k in a.kernels.split(",") if k], "model_sources": []}
    with open(os.path.join(out, "kernel-metadata.json"), "w") as f:
        json.dump(meta, f, indent=2)
    print(f"built {out} ({os.path.getsize(os.path.join(out, 'run.py')) / 1024:.0f} KB script)")


if __name__ == "__main__":
    main()
