#!/usr/bin/env python
"""
Summarise a GPU sweep: mean ± standard deviation over seeds for every run type,
the released-Nebula baseline on the same test set, and paired per-seed
differences. Writes results/gpu/summary.md and results/gpu/summary.csv.

    python -m gpu.summarize_gpu --data ../hier_data/speakeasy --results results/gpu
"""
import argparse
import glob
import json
import os
import re

import numpy as np
import pandas as pd

from hier_nebula.train import metrics

METRICS = [("auc", "AUC"), ("tpr@fpr=0.001", "TPR @ FPR 0.1%"), ("tpr@fpr=0.01", "TPR @ FPR 1%"),
           ("tpr@fpr=0.1", "TPR @ FPR 10%")]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--results", default="results/gpu")
    a = ap.parse_args()
    meta = pd.read_csv(os.path.join(a.data, "meta.csv"))
    base = np.load(os.path.join(a.data, "nebula_score_chunk0.npy"))

    rows, scores = [], {}
    for f in sorted(glob.glob(os.path.join(a.results, "*_seed*", "result.json"))):
        d = os.path.dirname(f)
        m = re.match(r"(.+)_seed(\d+)$", os.path.basename(d))
        run, seed = m.group(1), int(m.group(2))
        res = json.load(open(f))
        sc = pd.read_csv(os.path.join(d, "test_scores.csv"))
        scores[(run, seed)] = sc.set_index("row").score
        rows.append({"run": run, "seed": seed, "best_epoch": res.get("best_epoch")})
    if not rows:
        raise SystemExit(f"no finished runs in {a.results}")
    R = pd.DataFrame(rows)

    # rows every run was tested on (the full testset in a normal sweep)
    common = set.intersection(*[set(v.index) for v in scores.values()])
    test_rows = np.array(sorted(common))
    if len(test_rows) == 0:
        raise SystemExit("runs share no test rows; were they run with different --limit settings?")
    y = meta.label.values[test_rows]
    neb = metrics(y, base[test_rows], 1)
    for i, r in R.iterrows():
        for k, v in metrics(y, scores[(r.run, r.seed)].loc[test_rows].values, 1).items():
            R.loc[i, k] = v
    R.to_csv(os.path.join(a.results, "summary.csv"), index=False)

    md = ["# GPU sweep: test-set results (Speakeasy testset)", "",
          f"Test samples: {len(test_rows):,} ({int(y.sum()):,} malware, {int((y == 0).sum()):,} benign). "
          "Mean ± standard deviation over seeds; n = number of seeds. Generated by `gpu/summarize_gpu.py`.", "",
          "| model | n | " + " | ".join(n for _, n in METRICS) + " | best epoch |",
          "|---|---|" + "---|" * len(METRICS) + "---|",
          "| Nebula (released weights, first 512 tokens) | – | " +
          " | ".join(f"{neb[k]:.4f}" for k, _ in METRICS) + " | – |"]
    for run, g in R.groupby("run", sort=False):
        cells = [f"{g[k].mean():.4f} ± {g[k].std(ddof=1) if len(g) > 1 else 0:.4f}" for k, _ in METRICS]
        md.append(f"| {run} | {len(g)} | " + " | ".join(cells) + f" | {', '.join(map(str, g.best_epoch))} |")

    # paired per-seed differences (same seed = same validation split and level-2 initialisation)
    md += ["", "## Paired differences per seed", "",
           "Each row: one run minus the other, seed by seed, then mean ± standard deviation and how many "
           "seeds were better. A difference is convincing when it is positive for (almost) every seed.", "",
           "| comparison | metric | mean difference | std | seeds better / total |", "|---|---|---|---|---|"]
    runs = list(dict.fromkeys(R.run))
    pairs = [(r, "k1_cls") for r in runs if r != "k1_cls" and "k1_cls" in runs]
    for r1, r2 in pairs:
        for k, name in METRICS:
            d = []
            for s in sorted(set(R[R.run == r1].seed) & set(R[R.run == r2].seed)):
                d.append(R[(R.run == r1) & (R.seed == s)][k].iloc[0] - R[(R.run == r2) & (R.seed == s)][k].iloc[0])
            if d:
                md.append(f"| {r1} − {r2} | {name} | {np.mean(d):+.4f} | {np.std(d, ddof=1) if len(d) > 1 else 0:.4f} | "
                          f"{sum(x > 0 for x in d)} / {len(d)} |")
    for r in runs:
        for k, name in METRICS:
            d = R[R.run == r][k].values - neb[k]
            md.append(f"| {r} − Nebula | {name} | {d.mean():+.4f} | {d.std(ddof=1) if len(d) > 1 else 0:.4f} | "
                      f"{int((d > 0).sum())} / {len(d)} |")

    # AUC by report length
    nch = meta.n_chunks.values[test_rows]
    md += ["", "## AUC by report length (mean over seeds)", "",
           "| chunks | n | Nebula | " + " | ".join(runs) + " |", "|---|---|---|" + "---|" * len(runs)]
    for lo, hi, label in [(1, 1, "1 (fits in 512)"), (2, 3, "2–3"), (4, 8, "4–8")]:
        sel = (nch >= lo) & (nch <= hi)
        cells = []
        for r in runs:
            v = [metrics(y[sel], scores[(r, s)].loc[test_rows].values[sel], 1)["auc"]
                 for s in sorted(R[R.run == r].seed)]
            cells.append(f"{np.mean(v):.4f}")
        md.append(f"| {label} | {int(sel.sum()):,} | {metrics(y[sel], base[test_rows][sel], 1)['auc']:.4f} | "
                  + " | ".join(cells) + " |")

    env = os.path.join(a.results, "env.txt")
    if os.path.exists(env):
        md += ["", "## Run conditions", "", "```", open(env).read().strip(), "```"]
    out = os.path.join(a.results, "summary.md")
    with open(out, "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
