#!/usr/bin/env python
"""
Compare test-set results of the two-level runs with Nebula and a length-only
baseline. Writes results/hier/summary.md.

    python -m hier_nebula.summarize --data ../hier_data/speakeasy --runs results/hier/frozen_k1 results/hier/frozen_k8
"""
import argparse
import json
import os

import numpy as np
import pandas as pd

from hier_nebula.train import metrics


def threshold_at_fpr(y, s, fpr):
    neg = np.sort(s[y == 0])[::-1]
    k = int(np.floor(fpr * len(neg)))
    return neg[k] if k < len(neg) else -np.inf      # score > threshold => flagged


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", required=True)
    ap.add_argument("--runs", nargs="+", required=True)
    ap.add_argument("--out", default="results/hier/summary.md")
    ap.add_argument("--compare", nargs="*", default=[],
                    help="pairs 'i,j' of model indices (order of the per-family table) to bootstrap i minus j")
    ap.add_argument("--n-boot", type=int, default=1000)
    a = ap.parse_args()
    meta = pd.read_csv(os.path.join(a.data, "meta.csv"))
    base = np.load(os.path.join(a.data, "nebula_score_chunk0.npy"))

    scores = {}
    first = pd.read_csv(os.path.join(a.runs[0], "test_scores.csv"))
    rows = first.row.values
    y = meta.label.values[rows]
    scores["Nebula (released weights, first 512 tokens)"] = base[rows]
    scores["length only (number of tokens)"] = meta.n_tokens_full.values[rows].astype(float)
    for r in a.runs:
        res = json.load(open(os.path.join(r, "result.json")))
        ts = pd.read_csv(os.path.join(r, "test_scores.csv")).set_index("row").loc[rows, "score"].values
        args = res["args"]
        scores[f"two-level, {args['mode']} level 1, K={args['max_chunks']} chunks"] = ts

    md = ["# Two-level Nebula: test-set results (Speakeasy testset)\n",
          f"Test samples: {len(rows):,} ({int(y.sum()):,} malware, {int((y == 0).sum()):,} benign). "
          "All models see the same samples. Generated by `hier_nebula/summarize.py`.\n",
          "| model | AUC | TPR @ FPR 0.1% | TPR @ FPR 1% | TPR @ FPR 10% | F1 @ 0.5 |",
          "|---|---|---|---|---|---|"]
    for name, s in scores.items():
        m = metrics(y, s, 1)
        f1 = f"{m['f1@0.5']:.4f}" if "length" not in name else "–"
        md.append(f"| {name} | {m['auc']:.4f} | {m['tpr@fpr=0.001']:.4f} | {m['tpr@fpr=0.01']:.4f} | "
                  f"{m['tpr@fpr=0.1']:.4f} | {f1} |")

    names = [n for n in scores if "length" not in n]
    # paired bootstrap: is a difference bigger than test-set noise?
    if a.compare:
        from sklearn.metrics import roc_auc_score, roc_curve
        def tpr_at(yy, ss, f):
            fpr, tpr, _ = roc_curve(yy, ss)
            return tpr[fpr <= f].max()
        rng = np.random.default_rng(0)
        boots = [rng.integers(0, len(y), len(y)) for _ in range(a.n_boot)]
        md += ["", f"## Paired bootstrap of differences ({a.n_boot} resamples of the test set)", "",
               "Each resample draws test samples with replacement; both models are scored on the same draw. "
               "95% interval = 2.5th–97.5th percentile of the difference. An interval that contains 0 means "
               "the difference is within test-set noise. This does not cover training randomness (one seed per run).", "",
               "| comparison | metric | difference | 95% interval |", "|---|---|---|---|"]
        for pair in a.compare:
            n1, n2 = [names[int(i)] for i in pair.split(",")]
            for metric, fn in [("AUC", roc_auc_score), ("TPR @ FPR 0.1%", lambda yy, ss: tpr_at(yy, ss, 1e-3)),
                               ("TPR @ FPR 1%", lambda yy, ss: tpr_at(yy, ss, 1e-2))]:
                point = fn(y, scores[n1]) - fn(y, scores[n2])
                d = [fn(y[b], scores[n1][b]) - fn(y[b], scores[n2][b]) for b in boots]
                lo, hi = np.percentile(d, [2.5, 97.5])
                md.append(f"| {n1} **minus** {n2} | {metric} | {point:+.4f} | [{lo:+.4f}, {hi:+.4f}] |")

    # per family detection rate at the threshold giving 1% FPR on test benign
    md += ["", "## Detection rate per family at 1% false-positive rate",
           "", "Threshold chosen on the test benign samples so that 1% of them are flagged; "
           "cell = share of that family's test samples flagged (raw count). "
           "`clean`/`windows_syswow64` rows show the false-positive rate.", ""]
    fam = meta.family.values[rows]
    md.append("| family | n | " + " | ".join(names) + " |")
    md.append("|---|---|" + "---|" * len(names))
    thr = {n: threshold_at_fpr(y, scores[n], 0.01) for n in names}
    for f in sorted(set(fam)):
        sel = fam == f
        cells = []
        for n in names:
            flagged = scores[n][sel] > thr[n]
            cells.append(f"{100 * flagged.mean():.1f}% ({int(flagged.sum()):,})")
        md.append(f"| {f} | {int(sel.sum()):,} | " + " | ".join(cells) + " |")

    # by number of chunks: does reading more chunks help the long samples?
    nch = meta.n_chunks.values[rows]
    md += ["", "## AUC by report length (number of 512-token chunks)", "",
           "| chunks | n | malware share | " + " | ".join(names) + " |", "|---|---|---|" + "---|" * len(names)]
    for lo, hi, label in [(1, 1, "1 (fits in 512)"), (2, 3, "2–3"), (4, 8, "4–8")]:
        sel = (nch >= lo) & (nch <= hi)
        if len(set(y[sel])) < 2:
            continue
        cells = [f"{metrics(y[sel], scores[n][sel], 1)['auc']:.4f}" for n in names]
        md.append(f"| {label} | {int(sel.sum()):,} | {100 * y[sel].mean():.1f}% | " + " | ".join(cells) + " |")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as fh:
        fh.write("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
